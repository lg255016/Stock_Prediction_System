"""來源能力宣告（Source Capability Declaration）。

UG-G2-SB5 決策點 5（PO 2026-08-28 裁決，2026-08-30 核准實作）；
契約條文見 `FEATURE_REGISTRY.md` §5.7，決策記錄見 DEC-028。

**這個模組宣告的是「這個來源在結構上**能不能**提供某項資料」，
不是「這一次**有沒有**抓到」。**

後者是 `NULL` 的既有語意（`FEATURE_REGISTRY.md`:384-394：
「文章存在，留言尚未解析」）。兩者不得混用——用同一個值裝兩種語意，
正是本專案已經吃過兩次虧的病：

- `engagement_metric` 一欄兩義（PTT 帶符號推噓淨值 vs 其他來源的非負計數）
- `UG-G2-SB3` 的 `push_count` 雙語意型態陷阱

**為什麼需要這個概念**：`push_ratio` 不是本專案設計出來的指標——
它之所以存在，純粹是因為 **PTT 的資料結構本來就提供推／噓標記**。
要讓沒有這種標記的來源產生方向，得對**每則留言的文字**做 NLP，
而本系統只對**標題**做 NLP（`nlp_processor`），結構上做不到。

因此三個留言特徵對來源的要求並不相同：

| 特徵 | 需要什麼 | 無方向來源 |
|------|---------|-----------|
| `comment_volume_ratio` | 只要**數量** | 可算，且可跨來源相加 |
| `comment_polarization` | 需要**方向** | **結構上不可能** |
| `net_push_momentum`    | 需要**方向** | **結構上不可能** |

**刻意不建一般化的來源能力協商層**（PO 機械要求 3）：
現在只有一個真實需求，先建協商層是為想像中的第二個需求付設計費，
而那個需求的形狀還不知道。本宣告表可擴充即可。

================================================================================
⚠ 擴充本表之前先讀這一段（UG-G2-SB7 第 5 項，2026-09-05）
================================================================================
下面 `provides_comment_direction()` 的預設方向（**未登錄 → 無方向**）是對的設計，
理由寫在它自己的 docstring 裡：漏登錄「誠實地少」，反過來設計會「安靜地錯」。

**而它同時就是漏登錄不會被發現的原因。**

實際發生的事：第 5 項把 PTT 取數模式由逐關鍵字搜尋改為看板固定頁面，
`source` 值因此由 `ptt_stock` 變成 `ptt_board_pages`（見 §3.5A）。
新值不在本表裡，於是 `comment_polarization` 與 `net_push_momentum`
**對每一列新資料安靜地變 NULL** ——
而那兩個特徵用的是同一批 PTT 內頁，**方向能力一點都沒少**。

它不會報錯、不會讓任何測試變紅，只會讓兩欄全空。

> **一個 fail-safe 的預設，讓漏登錄變成一件不痛的事。**
> **不痛的事不會被記得 —— 所以它需要一個檢查，而不是靠記得。**

那個檢查是 `tests/test_ptt_board_pages.py` 的 **V12**：
它把本表與 `src/extractors/ptt_scraper.py` 的三個 `SOURCE_*` 常數對照，
**並帶一個反向釘子**（`dcard`／`threads` 仍須無方向），
以免有人為了讓 V12 過而把本表改成「全部都算」——
那正好會把上面說的「安靜地錯」做出來。

**下一次在這裡新增來源時**：問「有沒有東西會在我漏登錄時變紅？」
沒有的話，先補那個檢查。
"""
from __future__ import annotations

# 提供留言方向（推／噓標記）的來源。
#
# 新增來源時在此登錄，而不是在聚合層寫 if。
#
# ⚠⚠ **PTT 的三個值全部登錄**（UG-G2-SB7 第 5 項，2026-09-05）。
# 它們是**同一個站台的三種取數模式**（`MULTI_SOURCE_DATA_CONTRACT.md` §3.5A），
# 留言方向來自同一批內頁，**能力一點都沒少**。
#
# 這裡漏一個會怎樣：`provides_comment_direction()` 對該模式的**每一列**回傳
# `False`，`comment_polarization` 與 `net_push_momentum` 安靜地全變 `NULL`。
# **本模組的預設方向是刻意 fail-safe 的（見下方 docstring），
# 而那正是這個漏登錄不會報錯的原因** —— 少掉的特徵不拋例外、不讓測試變紅。
# 因此由 `tests/test_ptt_board_pages.py` 的 **V12** 對照 `ptt_scraper` 的三個常數。
#
# **刻意寫字面值而不 import `ptt_scraper`**：那會把 `requests`／`bs4`／`tenacity`
# 拉進 transform 層。同 `SOCIAL_SENTIMENT_COLUMNS` 的形狀 ——
# 清單留在程式裡，**由測試釘住它與權威來源的落差**。
COMMENT_DIRECTION_SOURCES = frozenset({
    "ptt_stock",            # SOURCE_LEGACY
    "ptt_keyword_search",   # SOURCE_KEYWORD_SEARCH
    "ptt_board_pages",      # SOURCE_BOARD_PAGES
})


def provides_comment_direction(source) -> bool:
    """該來源的留言是否帶有方向（推／噓）標記。

    **未登錄的來源一律視為「不提供方向」。** 這個預設方向是刻意的：

    - 漏登錄的後果 → 方向類特徵為 `NULL`（**誠實地少**）
    - 反過來設計的後果 → 偽造訊號（**安靜地錯**）

    `comment_polarization = 1 - 0² = 1.0` 是「散戶意見最大分歧」這種強訊號，
    它不會報錯，只會讓模型學到一個不存在的模式。少一點永遠比錯得安靜好。
    """
    return source in COMMENT_DIRECTION_SOURCES


# ==========================================================================
# 特徵組成的允許清單（UG-G2-SB7 收尾，PO 2026-09-05 裁決）
# ==========================================================================
# ⚠⚠ **這張表回答的問題與上面那張不同，兩者不得混為一談。**
#
#   `COMMENT_DIRECTION_SOURCES` → 「這個來源**能不能**提供推／噓標記」（能力）
#   `FEATURE_SOURCE_ALLOWLIST`  → 「**要不要**讓它進訓練資料」（取樣組成）
#
# **`ptt_stock` 同時是前者的成員、且不在後者** ——
# 它**確實**提供推噓標記，排除的理由**不是能力不足**，是**取樣 regime 不同**。
# `tests/test_feature_source_allowlist.py` 有一條測試專門釘住這個差別，
# 因為本專案至今抓到的多數缺陷都是「兩個東西看起來是同一個」。
#
# --------------------------------------------------------------------------
# 為什麼 `ptt_stock` 被排除
# --------------------------------------------------------------------------
# 它是 `UG-G2-SB7` 第 5 項之前、以**逐關鍵字搜尋**取得的 331 列，
# 其中 76 列 `post_time` 錯誤（年份差 +1~+7，見 `e67d3d6`）。
#
# **但排除的理由不是那些錯誤的日期** —— 就算日期修對了，
# **逐關鍵字搜尋橫跨七年**與**看板固定頁面只涵蓋最近幾頁**
# 仍然是**兩種不同的取樣**。
#
# > **修正日期只解決「哪一天」，不解決「怎麼取到的」。**
#
# 混進特徵會讓 RISK-015 的覆蓋率量測失真 —— 而那正是我們要量的東西。
#
# --------------------------------------------------------------------------
# 為什麼是**允許**清單而不是**排除**清單
# --------------------------------------------------------------------------
# **兩者的失效方向相反**：
#
#   `source <> 'ptt_stock'`  → 日後新增來源而忘了登錄 → **自動進入特徵**
#   `source IN (...)`        → 日後新增來源而忘了登錄 → **不會進入**
#
# 判準與上面 `provides_comment_direction()` 的預設方向**完全相同**：
# **漏登錄的後果應該是「誠實地少」，不是「安靜地錯」。**
#
# 而允許清單**自我說明** —— 它直接寫出哪些 regime 在特徵集裡。
#
# **權威定義在 `MULTI_SOURCE_DATA_CONTRACT.md` §3.5B**，這裡是它的程式落點。
FEATURE_SOURCE_ALLOWLIST = frozenset({
    "ptt_keyword_search",   # 逐關鍵字搜尋（現行程式仍可用）
    "ptt_board_pages",      # 看板固定頁面 + 記憶體比對（現行預設）
})


def source_enters_features(source) -> bool:
    """該來源的文章是否納入 `daily_ml_features` 的計算。

    **未登錄的來源一律不納入。** 這個預設方向是刻意的，
    理由與 `provides_comment_direction()` 相同：

    - 漏登錄的後果 → 該來源的文章不進特徵（**誠實地少**）
    - 反過來設計的後果 → **一個沒有人檢視過的取樣 regime 靜默混入訓練資料**，
      不會報錯，只會讓模型學到我們沒打算給它的東西
    """
    return source in FEATURE_SOURCE_ALLOWLIST
