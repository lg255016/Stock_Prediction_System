# src/extractors/retry_policy.py
"""DEC-032 的重試判別，**一份實作，兩個以上的呼叫端共用**。

================================================================================
為什麼是共用模組而不是各檔各寫一份
================================================================================
DEC-032 的 §Remaining Risks 自己寫著：

> **本規則未機械強制**：目前靠各腳本自行實作。`UG-G2-SB9` 實測顯示
> **同一個規則實作在一支腳本而不在另一支**，是本 SB 第六次同型缺陷。

**把判別式複製兩份，就是那句話描述的情形。** 共用模組不能讓規則被強制執行
（新腳本仍可能不呼叫它），**但至少讓「兩處行為不一致」變成不可能**。

================================================================================
判別依據：**有沒有拿到 `status_code`**，不是例外類別名稱
================================================================================
DEC-032 §Decision 逐字：

> **判別依據是「有沒有拿到 `status_code`」，不是例外類別名稱**
> ——後者需要窮舉，而窮舉不完的那一項會被靜默歸錯類。

| 情形 | 語意 | 處置 |
|------|------|------|
| 拿不到 `status_code` | 傳輸層失敗——服務**連我們問了什麼都還不知道** | **有界重試** |
| `status_code` 為 5xx | 服務**沒能回答** | **有界重試** |
| `status_code` 為 4xx（含 403／429） | 服務**在叫你停**／我們問錯了 | **硬停，一次都不重試** |

> **為何 4xx 整段不重試，而不是只挑 403／429**：
> DEC-032 點名 403／429 是因為它們是**實際會遇到**的拒絕形式，
> 但 4xx 的共同語意是「問題在請求端」——**重試同一個請求不會讓它變對**。
> 只挑兩個狀態碼等於維持一份需要窮舉的清單，而那正是上面那句話要避免的。
> ⚠ **這是對 DEC-032 的擴大解釋，不是它的逐字條文**，故寫在這裡而非默默實作。

================================================================================
本模組**不**負責的事
================================================================================
- **不決定重試次數與退避** —— 那是呼叫端的 `stop=`／`wait=`，因來源而異。
- **不記錄嘗試次數** —— 雙軌計數屬呼叫端（`etl_run_log.http_attempts`）。
- **不處理 `yfinance`** —— 該路徑拿不到 `status_code`，
  且 `Ticker.history` 把 HTTP 細節吞掉，**判別依據在那裡不適用**
  （提案 §0.1a）。
"""

import requests


def has_status_code(exc) -> bool:
    """例外是否帶著一個伺服器實際回覆的 `status_code`。"""
    response = getattr(exc, "response", None)
    return response is not None and getattr(response, "status_code", None) is not None


def is_retriable(exc) -> bool:
    """DEC-032：僅「服務沒能回答」與「服務還不知道我們問什麼」可重試。

    Returns:
        True  —— 傳輸層失敗，或 5xx。
        False —— 4xx（含 403／429），或任何非請求類的例外。
    """
    if not isinstance(exc, requests.exceptions.RequestException):
        # 解析錯誤、程式錯誤等：重試不會改變結果。
        return False
    if not has_status_code(exc):
        # 連線／逾時／TLS 交握失敗——**在任何 path 或 query 送出之前就失敗了**，
        # 伺服器根本不知道我們要問什麼，因此與「服務拒絕」無關（DEC-032 §Rationale）。
        return True
    return 500 <= exc.response.status_code < 600
